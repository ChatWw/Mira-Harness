import { createRequire } from 'node:module'
import { readFileSync, writeFileSync, existsSync, mkdirSync, copyFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

// Build-time generated data: TypeScript's Apache-2.0 lib declarations remain verbatim.
// Adapted from ZCode dynamic-workflow/scripts/generate-libs.mjs, Apache-2.0.
// Copyright 2026 Z.AI Co., Ltd.; see third-party-licenses/zcode.
// Mira changes: local output paths and TypeScript license archival.
const require = createRequire(import.meta.url)
const packagePath = require.resolve('typescript/package.json')
const version = JSON.parse(readFileSync(packagePath, 'utf8')).version
const notices = fileURLToPath(new URL('../third-party-licenses/typescript/', import.meta.url))
mkdirSync(notices, { recursive: true })
copyFileSync(join(dirname(packagePath), 'LICENSE.txt'), join(notices, 'LICENSE.txt'))
copyFileSync(join(dirname(packagePath), 'ThirdPartyNoticeText.txt'), join(notices, 'NOTICE.txt'))
const output = fileURLToPath(new URL('../packages/mira-flow-kit/src/compiler/mira-libs.generated.ts', import.meta.url))
if (existsSync(output) && readFileSync(output, 'utf8').includes(`export const TS_LIB_VERSION = ${JSON.stringify(version)};`)) process.exit(0)

const libraryRoot = join(dirname(packagePath), 'lib')
const libraries = {}
const pending = ['lib.es2022.d.ts']
const reference = /\/\/\/\s*<reference\s+lib\s*=\s*["']([^"']+)["']\s*\/>/g
while (pending.length) {
  const file = pending.shift()
  if (Object.hasOwn(libraries, file)) continue
  const text = readFileSync(join(libraryRoot, file), 'utf8')
  libraries[file] = text
  for (const match of text.matchAll(reference)) pending.push(`lib.${match[1]}.d.ts`)
}
const entries = Object.keys(libraries).sort().map(file => `  ${JSON.stringify(file)}: ${JSON.stringify(libraries[file])},`).join('\n')
writeFileSync(output, `// Generated by scripts/generate-mira-flow-libs.mjs; do not edit.\n// TypeScript standard library declarations: Apache-2.0, original notices retained.\nexport const TS_LIB_VERSION = ${JSON.stringify(version)};\nexport const TS_LIBS: Record<string, string> = {\n${entries}\n};\n`)
console.log(`Mira flow compiler: embedded ${Object.keys(libraries).length} TypeScript ${version} libraries`)
